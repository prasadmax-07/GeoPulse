
USE DATABASE GEOPULSE_DB;
USE SCHEMA MOBILITY;
USE WAREHOUSE COMPUTE_WH;

-- 1. Hourly Traffic Analysis
SELECT
    EXTRACT(HOUR FROM TIMESTAMP) AS HOUR,
    COUNT(*) AS TOTAL_PINGS,
    COUNT(DISTINCT DEVICEID) AS UNIQUE_DEVICES
FROM GPS_MOBILITY_DATA
GROUP BY HOUR
ORDER BY HOUR;


-- 2. Zone-wise Mobility Analysis
SELECT
    LOCATIONZONE,
    COUNT(*) AS TOTAL_PINGS,
    COUNT(DISTINCT DEVICEID) AS UNIQUE_DEVICES
FROM GPS_MOBILITY_DATA
GROUP BY LOCATIONZONE
ORDER BY TOTAL_PINGS DESC;


-- 3. Device Activity Summary
SELECT
    DEVICEID,
    COUNT(*) AS TOTAL_PINGS,
    MIN(TIMESTAMP) AS FIRST_ACTIVITY,
    MAX(TIMESTAMP) AS LAST_ACTIVITY
FROM GPS_MOBILITY_DATA
GROUP BY DEVICEID
ORDER BY TOTAL_PINGS DESC;
